'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),Module=require('node:module'),ts=require('typescript');
const sourcePath=path.resolve(__dirname,'../src/diagnostics/driveabilityAdvisor.ts');
const compiled=ts.transpileModule(fs.readFileSync(sourcePath,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2019}}).outputText;
const m=new Module(sourcePath,null);m.filename=sourcePath;m.paths=Module._nodeModulePaths(path.dirname(sourcePath));m._compile(compiled,sourcePath);
const assess=m.exports.assessDriveability;
const sample=(overrides={})=>assess({ecuConnected:true,speedKmh:40,consumptionKml:5,fuelType:'ETANOL',...overrides});
assert.equal(sample({ecuConnected:false}).code,'ECU_DISCONNECTED');
assert.equal(sample({speedKmh:null}).code,'WAITING_MOVEMENT');
assert.equal(sample({speedKmh:9.9}).code,'WAITING_MOVEMENT');
assert.equal(sample({consumptionKml:null}).code,'NO_DATA');
assert.equal(sample({consumptionKml:0}).code,'NO_DATA');
assert.equal(sample({consumptionKml:4.49}).code,'ELEVATED');
assert.equal(sample({consumptionKml:6}).code,'BALANCED');
assert.equal(sample({consumptionKml:7}).code,'EFFICIENT');
assert.equal(sample({fuelType:'GASOLINA',consumptionKml:6.4}).code,'ELEVATED');
assert.equal(sample({fuelType:'GASOLINA',consumptionKml:8}).code,'BALANCED');
assert.equal(sample({fuelType:'GASOLINA',consumptionKml:10}).code,'EFFICIENT');
assert.equal(sample({fuelType:'FLEX',consumptionKml:8}).code,'BALANCED');
assert.equal(sample({fuelType:'FLEX',consumptionKml:10}).code,'EFFICIENT');
assert.equal(sample({speedKmh:0,consumptionKml:40}).code,'WAITING_MOVEMENT');
console.log('driveabilityAdvisor.test.js: OK');
