'use strict';
const assert = require('assert');
const path = require('path');
const ts = require('typescript');
const Module = require('module');
const file = path.resolve(__dirname, '../src/obd/extendedPidDiscovery.ts');
const source = require('fs').readFileSync(file, 'utf8');
const js = ts.transpileModule(source, {compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2019}}).outputText;
const mod = new Module(file, module);
mod.filename = file;
mod.paths = Module._nodeModulePaths(path.dirname(file));
const oldLoad = Module._load;
Module._load = function(request) { if(request === 'expo-file-system') return {}; return oldLoad.apply(this, arguments); };
mod._compile(js, file);
Module._load = oldLoad;
const api = mod.exports;
async function run() {
 assert.deepStrictEqual(api.decodeExtendedSupportBitmap('0900','49 00 90 00 00 00','09'),['01','04']);
 assert.deepStrictEqual(api.decodeExtendedSupportBitmap('0600','46 00 80 00 00 00','06'),['01']);
 assert.deepStrictEqual(api.decodeExtendedSupportBitmap('0100','41 00 80 00 00 00','09'),[]);
 assert.deepStrictEqual(api.decodeExtendedSupportBitmap('0900','NO DATA','09'),[]);
 const seen=[];
 const data={'0900':['49 00 90 00 00 00','OK'],'0600':['46 00 80 00 00 00','OK'],'0901':['49 01 01','OK'],'0904':['49 04 01 41 42 43','OK']};
 const report=await api.discoverExtendedObdData({async executeCommand(command){seen.push(command);const x=data[command]||['NO DATA','ERROR'];return {response:x[0],status:x[1],elapsedMs:10};}},'KWP FAST');
 assert.deepStrictEqual(seen,['0900','0600','0901','0904']);
 assert(!seen.includes('0902'));
 assert.deepStrictEqual(report.supportedMode09InfoTypes,['01','04']);
 assert.deepStrictEqual(report.supportedMode06MonitorIds,['01']);
 assert.strictEqual(report.source,'REAL_OBD');
 console.log('Extended PID discovery tests passed');
}
run().catch(error=>{console.error(error);process.exitCode=1;});
