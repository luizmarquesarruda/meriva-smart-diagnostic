const assert = require('assert');
const fs = require('fs');

const packageJson = JSON.parse(fs.readFileSync('package.json', 'utf8'));
const appJson = JSON.parse(fs.readFileSync('app.json', 'utf8'));
const gps = fs.readFileSync('src/gps/gpsTracker.ts', 'utf8');
const task = fs.readFileSync('src/gps/backgroundLocationTask.ts', 'utf8');
const monitoring = fs.readFileSync('src/gps/backgroundMonitoring.ts', 'utf8');
const shared = fs.readFileSync('src/obd/sharedConnection.ts', 'utf8');
const layout = fs.readFileSync('app/_layout.tsx', 'utf8');
const autoTrip = fs.readFileSync('src/trip/autoTripService.ts', 'utf8');
const keepAwakePackage = require('../package.json').dependencies['expo-keep-awake'];
const permissions = fs.readFileSync('src/permissions/permissionManager.ts', 'utf8');
const settingsScreen = fs.readFileSync('app/configuracoes.tsx', 'utf8');
const lock = JSON.parse(fs.readFileSync('package-lock.json', 'utf8'));

assert.strictEqual(packageJson.dependencies['expo-task-manager'], '~11.8.2');
assert.strictEqual(lock.packages[''].dependencies['expo-task-manager'], '~11.8.2');
assert.strictEqual(lock.packages['node_modules/expo-task-manager'].version, '11.8.2');
assert.strictEqual(keepAwakePackage, '~13.0.2');
assert.strictEqual(lock.packages[''].dependencies['expo-keep-awake'], '~13.0.2');
assert.strictEqual(lock.packages['node_modules/expo-keep-awake'].version, '13.0.2');
assert(layout.includes("import { activateKeepAwakeAsync, deactivateKeepAwake } from 'expo-keep-awake'"));
assert(layout.includes("activateKeepAwakeAsync(tag)"), 'tela deve ser mantida ligada com ativação explícita');
assert(layout.includes("AppState.addEventListener('change'"), 'bloqueio de tela deve acompanhar o ciclo de vida do app');
assert(layout.includes("if (state === 'active') activate()"), 'bloqueio de tela deve ser reativado ao voltar ao primeiro plano');
assert(layout.includes('deactivateKeepAwake(tag)'), 'bloqueio deve ser liberado ao sair do app e desmontar a raiz');
assert.strictEqual(lock.packages['node_modules/unimodules-app-loader'].version, '4.6.0');

assert(appJson.expo.android.permissions.includes('ACCESS_BACKGROUND_LOCATION'));
const locationPlugin = appJson.expo.plugins.find((plugin) => Array.isArray(plugin) && plugin[0] === 'expo-location');
assert(locationPlugin, 'expo-location deve estar configurado como config plugin');
assert.strictEqual(locationPlugin[1].isAndroidBackgroundLocationEnabled, true);
assert.strictEqual(locationPlugin[1].isAndroidForegroundServiceEnabled, true);

assert(task.includes('TaskManager.defineTask(BACKGROUND_LOCATION_TASK_NAME'));
assert(task.includes('gpsTracker.handleLocation(location)'));
assert(gps.includes("BACKGROUND_LOCATION_TASK_NAME = 'meriva-smart-background-location'"));
assert(gps.includes('startLocationUpdatesAsync(BACKGROUND_LOCATION_TASK_NAME'));
assert(gps.includes('foregroundService:'));
assert(gps.includes('this.subscription?.remove();'));
assert(gps.includes('this.subscription = null;'));
assert(gps.includes('notificationTitle: \'MERIVA SMART — Diagnóstico OBD\''));
assert(gps.includes('handleLocation(location: Location.LocationObject)'));
assert(gps.includes('stopLocationUpdatesAsync(BACKGROUND_LOCATION_TASK_NAME)'));
assert(!gps.includes('if (!this.backgroundTaskRunning) return;'), 'stop deve consultar o TaskManager mesmo após recriação do JS');
assert(gps.includes('watchPositionAsync('));

assert(permissions.includes('requestBackgroundLocationPermissionsOnly'));
assert(permissions.includes('getBackgroundLocationPermissionOnly'));
assert(permissions.includes('requestBackgroundPermissionsAsync'));
assert(monitoring.includes('startBackgroundMonitoring'));
assert(monitoring.includes('getBackgroundLocationPermissionOnly'));
assert(!monitoring.includes('requestBackgroundLocationPermissionsOnly'), 'o serviço automático não pode pedir permissão de background');
assert(!shared.includes('startBackgroundMonitoring'), 'sharedConnection não deve iniciar GPS');
assert(!shared.includes('stopBackgroundMonitoring'), 'sharedConnection não deve administrar o ciclo de vida GPS');
assert(autoTrip.includes('startBackgroundMonitoring()'), 'AutoTripService é o único dono do início GPS');
assert(autoTrip.includes('this.backgroundGpsEnabled'), 'background GPS exige preferência explícita');
assert(autoTrip.includes('applyBackgroundGpsPreference'), 'alterar opt-in deve aplicar a transição de GPS');
assert(autoTrip.includes('gpsTracker.start({ resetTrip: false })'), 'troca para foreground preserva distância acumulada');
assert(settingsScreen.includes('requestBackgroundLocationPermissionsOnly()'), 'a permissão de background só é solicitada na tela de configurações');
assert(layout.includes("import '../src/gps/backgroundLocationTask';"));
assert(!layout.includes('const startGps ='), 'layout não deve iniciar GPS independentemente da ECU');
assert(!layout.includes('startGps(settings.diagnosticAlerts)'), 'startup não deve criar trilha GPS sem ECU');
assert(autoTrip.includes('this.scheduleGpsStart(generation)'), 'GPS startup is scheduled only after ECU validation');
assert(!autoTrip.includes('await this.ensureGpsForEcu()'), 'GPS startup must not block serial OBD polling');
assert(autoTrip.includes('this.gpsStartPromise'), 'GPS must use a single in-flight startup owner');
assert(autoTrip.includes('GPS_START_RETRY_COOLDOWN_MS'), 'failed GPS startup must be throttled instead of prompting every OBD cycle');
assert(autoTrip.includes('if (!generationIsCurrent())'), 'late GPS startup must be cleaned after the trip/ECU generation ends');
assert(autoTrip.includes('await this.stopGpsForEcu()'), 'serviço de viagem para GPS quando ECU perde resposta/desconecta');
assert(autoTrip.includes("if (!getSharedObdStatus().ecuConnected)"), 'gravação deve exigir estado ECU conectado');

console.log('background execution: Android FGS + TaskManager + lifecycle: OK');
